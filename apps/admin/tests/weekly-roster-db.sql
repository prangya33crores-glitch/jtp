BEGIN;
SET LOCAL ROLE service_role;
DO $$
DECLARE w text; r integer; s jsonb; sh text; loc text; pol text; d date:=(now() AT TIME ZONE 'Asia/Kolkata')::date; result jsonb;
BEGIN
 SELECT id,revision INTO w,r FROM public.workspaces LIMIT 1;
 s:=public.jtp_workspace_state(w);
 sh:=s->'shifts'->0->>'id';loc:=s->'locations'->0->>'id';pol:=s->'policies'->0->>'id';
 ASSERT sh IS NOT NULL AND loc IS NOT NULL AND pol IS NOT NULL,'Required test masters missing';
 s:=jsonb_set(s,'{personnel}',(s->'personnel')||jsonb_build_array(
 jsonb_build_object('id','weekly-qa-1','code','WEEKLYQA1','name','Weekly QA 1','status','Active','joined','2020-01-01','salary',0),
 jsonb_build_object('id','weekly-qa-2','code','WEEKLYQA2','name','Weekly QA 2','status','Active','joined','2020-01-01','salary',0)));
 s:=jsonb_set(s,'{assignments}',(s->'assignments')||jsonb_build_array(
 jsonb_build_object('id','weekly-qa-original','person','weekly-qa-1','date',d,'shift',sh,'location',loc,'leader','','status','Published','autoSlot','qa-slot'),
 jsonb_build_object('id','weekly-qa-cover','person','weekly-qa-2','date',d,'shift',sh,'location',loc,'leader','','status','Published','replacesAssignment','weekly-qa-original','autoGenerated',true)));
 ASSERT public.jtp_write_workspace(w,s,r)=1,'Atomic normalized save failed';
 ASSERT public.jtp_write_workspace(w,s,r)=0,'Stale revision must not save';
 ASSERT EXISTS(SELECT 1 FROM public.duty_assignments WHERE workspace=w AND id='weekly-qa-cover' AND attributes->>'replacesAssignment'='weekly-qa-original'),'Replacement metadata missing';
 ASSERT public.jtp_mark_attendance(w,'weekly-qa-2',d,'weekly-qa-cover','qa','Admin') IS NULL,'Cover without approved original leave must be blocked';
 s:=jsonb_set(s,'{leaves}',(s->'leaves')||jsonb_build_array(jsonb_build_object('id','weekly-qa-leave','person','weekly-qa-1','policy',pol,'from',d,'to',d,'status','Approved','classification','Unpaid','type','QA','reason','Rollback verification')));
 ASSERT public.jtp_write_workspace(w,s,r+1)=1,'Leave save failed';
 result:=public.jtp_mark_attendance(w,'weekly-qa-2',d,'weekly-qa-cover','qa','Admin');
 ASSERT result->>'status'='Present','Active approved-leave cover attendance failed';
 ASSERT public.jtp_mark_attendance(w,'weekly-qa-2',d,'weekly-qa-cover','qa','Admin') IS NULL,'Duplicate attendance must be blocked';
 DELETE FROM public.attendance WHERE workspace=w AND person='weekly-qa-2';
 UPDATE public.leave_requests SET status='Cancelled' WHERE workspace=w AND id='weekly-qa-leave';
 ASSERT public.jtp_mark_attendance(w,'weekly-qa-2',d,'weekly-qa-cover','qa','Admin') IS NULL,'Cancelled leave cover must be blocked';
END $$;
ROLLBACK;
